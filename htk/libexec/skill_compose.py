"""Assemble a profile skill from shared instructions and profile additions."""

import re
from urllib.parse import urlsplit


def split_document(path):
    text = path.read_text()
    match = re.match(r"\A---\n(.*?)\n---\n(.*)\Z", text, re.S)
    if not match:
        raise ValueError(f"Skill needs YAML frontmatter: {path}")
    return match.group(1), match.group(2).strip()


def source_links(body, directory):
    """Keep links useful when the assembled SKILL.md lives outside its sources."""
    def replace(match):
        target = match.group(1)
        if target.startswith("<") and target.endswith(">"):
            target = target[1:-1]
        if target.startswith(("#", "/", "~")) or urlsplit(target).scheme:
            return match.group(0)
        path, separator, fragment = target.partition("#")
        target = str((directory / path).resolve()) + separator + fragment
        if any(char.isspace() for char in target):
            target = "<" + target + ">"
        return "](" + target + ")"

    # Examples inside code fences are data, not links in the skill itself.
    lines = []
    fence = None
    for line in body.splitlines(keepends=True):
        marker = re.match(r"^\s*(`{3,}|~{3,})", line)
        if marker:
            value = marker.group(1)
            if fence is None:
                fence = value
            elif value[0] == fence[0] and len(value) >= len(fence):
                fence = None
            lines.append(line)
        else:
            lines.append(line if fence else re.sub(r"\]\(([^)\n]+)\)", replace, line))
    return "".join(lines)


def compose(core, *profiles):
    """The last profile supplies metadata; ordered source bodies retain their links."""
    sources = [core, *profiles]
    documents = [split_document(path) for path in sources]
    metadata = documents[-1][0]
    return (f"---\n{metadata}\n---\n\n"
            "<!-- Generated by htk install from the selected profile skill sources. -->\n\n"
            + "\n\n".join(source_links(body, path.parent)
                            for path, (_, body) in zip(sources, documents)) + "\n")
